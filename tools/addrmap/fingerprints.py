"""Write (or check) the image checks of a base table: CHECKS at the end of mods/m1/bases/<table>.py.

    python -I fingerprints.py stock_161 ~/bento/stock-1.6.1/bento1.bin           # rewrite CHECKS
    python -I fingerprints.py stock_161 ~/bento/stock-1.6.1/bento1.bin --check   # only compare

For every code / data entry: fp = the first 16 hex digits of sha256 over the 16 image bytes at its
address. For every RAM entry: lits = how many aligned words of the image equal it. build.py
verifies both on every build (bases.Base.verify_image), so an address changed in a table without
being looked at in the image again is refused. Rerun this after deliberately changing an address,
and say in the entry's note how you checked it. Only hashes and counts are stored, never image bytes.
"""
import argparse, hashlib, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
M1 = os.path.join(HERE, "..", "..", "mods", "m1")
sys.path.insert(0, M1)
import bases

MARK = "# " + "-" * 64 + " image checks"


def checks(b, img):
    """{name: (fp, lits)} for every entry of table b that gets an image check."""
    counts = bases.word_counts(img)
    out = {}
    for n, s in b.syms.items():
        c = bases.checked(s)
        if c == "fp":
            out[n] = (bases.fingerprint(img, s.value), None)
        elif c == "lits":
            out[n] = (None, counts[s.value])
    return out


def block(ch):
    L = [MARK,
         "# Generated by tools/addrmap/fingerprints.py from the stock image; do not edit by hand.",
         "# (fp: sha256 of the 16 bytes at a code / data address, first 16 hex digits; lits: literal count.)",
         "CHECKS = {"]
    for n, (fp, lits) in ch.items():
        L.append(f'    "{n}": ({fp!r}, {lits!r}),')
    L.append("}")
    return "\n".join(L) + "\n"


def write(path, ch):
    """Replace (or append) the CHECKS block of a table file, keeping its line endings."""
    raw = open(path, newline="").read()
    nl = "\r\n" if "\r\n" in raw else "\n"
    text = raw.replace("\r\n", "\n")
    i = text.find(MARK)
    head = text if i < 0 else text[:i]
    text = head.rstrip("\n") + "\n\n" + block(ch)
    open(path, "w", newline="").write(text.replace("\n", nl))


def main():
    p = argparse.ArgumentParser()
    p.add_argument("table")
    p.add_argument("image")
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    img = open(a.image, "rb").read()
    b = bases.load(a.table, allow_draft=True)
    if hashlib.sha256(img).hexdigest() != b.sha256:
        raise SystemExit(f"{a.image} is not {b.label}")
    if a.check:
        bad = b.verify_image(img)
        print("\n".join(bad) or f"{a.table}: image checks agree")
        return 1 if bad else 0
    ch = checks(b, img)
    write(os.path.join(M1, "bases", a.table + ".py"), ch)
    print(f"{a.table}: CHECKS for {len(ch)} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
