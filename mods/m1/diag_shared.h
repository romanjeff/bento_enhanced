/* M1 diagnostic: shared M7 -> M4 log layout (stock 1.6.1 + Lab CH10 1.6HA).
 *
 * Purpose: find which code turns a pad press on an External track into a
 * MIDI note-on, by logging every hop: pad event -> queue -> consumer ->
 * MIDI-out event -> cross-core MIDI ring. The M7 only writes RAM; the M4
 * formats and writes \BENTO_DIAG.log on its UI thread when the pads are idle.
 *
 * RAM (since v3.16; addresses below are 1.6.1's, S_D2_SLICE = 0x3003C000; the shared lines
 * are SLICE(offset) and move with the slice): our whole slice is 0x3003C000..0x3003C9A0, in the top of
 * D2 SRAM2 that no stock 1.6.1 linker section uses (M4 .bss ends 0x30036CF0, heap
 * 0x30036CF0..0x30037CF0, stack 0x30037CF0..0x300390F0; the M4 reset code
 * briefly uses a stack below 0x30040000; SRAM3 from 0x30040000 holds the MIDI
 * ring). M4 MPU region 2 maps 0x30000000..0x30080000; the M7 reaches it through
 * its default map (cacheable: same clean/invalidate rules as before). Until
 * v3.15 it lived at 0x24048400 by lowering the M7 heap end, which broke
 * loading large projects. Layout inside the slice is unchanged (offset -0x24048400
 * + 0x3003C000).
 * 1.6.8 (S2): stock owns that D2 (SAI DMA buffers, M7 MPU R14), so S_D2_SLICE is AXI 0x2404D000
 * (to 0x24050000), above the M7 stack. The M7 sees it write-back through MPU R1 (the same rules
 * below hold); the M4's MPU maps it as Device: M4 accesses must be naturally aligned (the M4
 * code is built -mstrict-align on 1.6.8, and the emulated tests fault any unaligned one).
 *
 * Ownership, one writer per 32-byte cache line (offsets into the slice):
 *   +0x100 M7 header   (M7 writes, M4 reads)
 *   +0x120 M4 header   (M4 writes, M7 never reads)
 *   +0x140 M7 private  diag: dedupe table 16 x 8 B
 *   +0x1C0 M7 private  diag: flags, generation
 *   +0x1E0 config      (M4 writes once at boot, M7 reads): M1 state region
 *   +0x200 M7 stats    (M7 writes, M4 reads): MIDI ring fill / overflows
 *   +0x2C0 records     (M7 writes, M4 reads), 17 x 48 bytes
 */
